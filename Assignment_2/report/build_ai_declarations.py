def para(doc, text, size=None, bold=None, italic=None, indent=0, space=2):
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(space)
    if indent:
        p.paragraph_format.left_indent = Pt(indent)
    r = p.add_run(text)
    r.bold, r.italic = bold, italic
    if size:
        r.font.size = Pt(size)
    return p


def block(doc, num, title, tools, items, flags, label, desc):
    para(doc, f"## {num}. {title}", 12.5, bold=True)
    para(doc, f"* Tool(s) Used: {tools}", indent=12)
    para(doc, "* Specific Applications:", indent=12, bold=True)
    for item, on in zip(items, flags):
        para(doc, f"   {BOX_YES if on else BOX_NO} {item}", indent=24)
    para(doc, f"* {label} {desc}", indent=12)


